"""报文装载 → 分指标质控门槛裁决 → 入栏 / 坏点 / 影子归档。"""
from __future__ import annotations

import json
import uuid

from app.db import 串行写
from app.seed import 此刻
from app.services import 校验, 时间

影子草稿 = "过门槛-影子草稿"


class 版本争用(Exception):
    """账册版本已被别的会话推进；本次写不得双成。"""


def _批次号(体: dict) -> str:
    前 = str(体.get("批次编号") or "探批").strip() or "探批"
    return f"{前}-{uuid.uuid4().hex[:8]}"


def _判(ev: dict, 门裁决: dict) -> tuple[str, str]:
    """返回 (分流标, 草稿裁决)。

    错阈：报文自报的门槛指标键与自身指标键不同 → 仅进影子归档，正式坏点。
    本指标：按本指标门槛裁决，入栏或坏点。
    无门槛：显式放行打标，不算影子草稿。
    """
    声明 = ev.get("门槛指标键")
    if 声明 and 声明 != ev["指标键"]:
        return "错指标门槛", 影子草稿
    if not 门裁决.get("受控", True):
        return 门裁决.get("分流", "无门槛-放行"), 门裁决["裁决"]
    return ("本指标门槛" if 门裁决["过门槛"] else "本指标越界"), 门裁决["裁决"]


def 装一批(体: dict) -> dict:
    try:
        return _装一批(体 or {})
    except 版本争用 as e:
        return {
            "批次编号": _批次号(体 or {}),
            "拒绝": True,
            "拒因": str(e),
            "入流": 0,
            "入栏": 0,
            "坏点": 0,
            "驳回": 0,
            "影子归档": 0,
            "明细": [],
        }


def _装一批(体: dict) -> dict:
    批次 = _批次号(体)
    报文 = 体.get("报文") or []
    报告 = {
        "批次编号": 批次, "入流": 0, "入栏": 0, "坏点": 0, "驳回": 0,
        "影子归档": 0, "明细": [],
    }
    预检 = 校验.校验批次(体)
    if 预检:
        报告["明细"].append({"命运": "批次预检", "说明": 校验.摘要错误(预检)})

    期望版 = 体.get("期望账册版本")
    仓时 = 此刻()

    with 串行写() as conn:
        规 = {r["键"]: r["值"] for r in conn.execute("SELECT 键,值 FROM 栏规").fetchall()}
        当前版 = int(规.get("账册版本", "1"))
        if 期望版 is not None:
            try:
                期望版 = int(期望版)
            except (TypeError, ValueError):
                raise 版本争用(f"期望账册版本非整数:{期望版!r}")
            if 期望版 != 当前版:
                raise 版本争用(f"账册版本冲突：期望{期望版} 实际{当前版}")
        指纹 = 校验.门槛指纹(规)
        栏号 = 规.get("当前栏号", "B-demo")
        站集合 = {r["源键"] for r in conn.execute("SELECT 源键 FROM 站点源").fetchall()}

        for ev in 报文:
            行错 = 校验.校验报文(ev)
            if 行错:
                报告["驳回"] += 1
                报告["明细"].append({"命运": "驳回-校验", "说明": 校验.摘要错误(行错)})
                continue
            try:
                时间.解析时(ev["观测时"])
            except Exception:
                报告["驳回"] += 1
                报告["明细"].append({"命运": "驳回-观测时", "说明": ev.get("观测时")})
                continue
            编号 = ev["报文编号"]
            if conn.execute("SELECT 1 FROM 观测报文 WHERE 报文编号=?", (编号,)).fetchone():
                报告["驳回"] += 1
                报告["明细"].append({"命运": "驳回-幂等", "说明": 编号})
                continue
            if ev["站点键"] not in 站集合:
                报告["驳回"] += 1
                报告["明细"].append({"命运": "驳回-未知站点", "说明": ev["站点键"]})
                continue

            读数 = float(ev["读数"])
            漂 = 时间.漂移秒(ev["观测时"], 仓时)
            门裁决 = 校验.分门槛裁决(读数, 规, ev["指标键"])
            分流, 草稿 = _判(ev, 门裁决)
            conn.execute(
                """INSERT INTO 观测报文(报文编号,站点键,指标键,读数,观测时,处理时,命运,批次编号,分流)
                   VALUES (?,?,?,?,?,?,?,?,?)""",
                (编号, ev["站点键"], ev["指标键"], 读数, ev["观测时"], 仓时,
                 "已装载", 批次, 分流),
            )
            报告["入流"] += 1

            # 错阈点：进只读影子归档，正式命运不得是「入栏」。
            if 分流 == "错指标门槛":
                conn.execute(
                    """INSERT INTO 影子归档
                       (报文编号,站点键,指标键,读数,观测时,草稿命运,原因,门槛指纹,只读,归档时)
                       VALUES (?,?,?,?,?,?,?,?,?,?)""",
                    (编号, ev["站点键"], ev["指标键"], 读数, ev["观测时"],
                     草稿, f"错指标门槛：本指标{ev['指标键']}，声明门槛{ev.get('门槛指标键')}",
                     指纹, 1, 仓时),
                )
                报告["影子归档"] += 1

            if 门裁决["裁决"] == "入栏":
                conn.execute(
                    """INSERT INTO 入栏缓冲
                       (报文编号,站点键,指标键,读数,观测时,栏号,命运,入栏时,门槛指纹)
                       VALUES (?,?,?,?,?,?,?,?,?)""",
                    (编号, ev["站点键"], ev["指标键"], 读数, ev["观测时"],
                     栏号, "在栏", 仓时, 指纹),
                )
                conn.execute("UPDATE 观测报文 SET 命运=? WHERE 报文编号=?", ("已入栏", 编号))
                报告["入栏"] += 1
                if 分流 == "本指标门槛":
                    报告["明细"].append({
                        "命运": "入栏", "报文编号": 编号, "栏号": 栏号,
                        "漂移秒": 漂, "受控": True, "分流": 分流, "门槛指纹": 指纹,
                    })
                else:
                    报告["明细"].append({
                        "命运": "入栏-放行", "报文编号": 编号, "栏号": 栏号,
                        "漂移秒": 漂, "分流": 分流,
                    })
            else:
                conn.execute(
                    """INSERT INTO 坏点匣(报文编号,站点键,原因,读数,观测时,入匣时,分流)
                       VALUES (?,?,?,?,?,?,?)""",
                    (编号, ev["站点键"], 门裁决["原因"], 读数, ev["观测时"], 仓时, 分流),
                )
                conn.execute("UPDATE 观测报文 SET 命运=? WHERE 报文编号=?", ("已坏点", 编号))
                报告["坏点"] += 1
                报告["明细"].append({
                    "命运": "坏点", "报文编号": 编号,
                    "原因": 门裁决["原因"], "分流": 分流,
                })

        conn.execute(
            """INSERT INTO 装载批次(编号,时刻,入流,入栏,坏点,报告) VALUES (?,?,?,?,?,?)""",
            (批次, 仓时, 报告["入流"], 报告["入栏"], 报告["坏点"],
             json.dumps(报告, ensure_ascii=False)),
        )
        # 写纪元推进：与改门槛同版争用时只许一路成，不得双成。
        新版 = 当前版 + 1
        conn.execute(
            "INSERT INTO 栏规(键,值) VALUES (?,?) ON CONFLICT(键) DO UPDATE SET 值=excluded.值",
            ("账册版本", str(新版)),
        )
        报告["账册版本"] = 新版
        报告["门槛指纹"] = 指纹
    return 报告
