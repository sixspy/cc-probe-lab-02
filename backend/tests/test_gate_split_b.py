"""失败测乙：对账把影子草稿当正式过门槛绿则红。

两轨：
- 现行轨：入栏缓冲只收「本指标、当前门槛指纹」过门槛集。
- 影子轨：错阈点/过时门槛点进只读归档（影子归档），对账不得计入正式。

若贯验把影子草稿（草稿命运=入栏）算进「汇总报文」而仍报对齐 → 红。
"""
from __future__ import annotations

from app.db import 连接
from app.services import 贯验, 目录, 校验, 装载, 结栏


浊度门 = {"门槛:浊度:下限": "0", "门槛:浊度:上限": "5"}


def _置(补丁: dict) -> dict:
    out = 目录.改栏规(补丁)
    assert "错误" not in out, out
    return out


def _汇总(指标: str) -> list:
    conn = 连接()
    try:
        return conn.execute(
            "SELECT * FROM 站点汇总账 WHERE 指标键=?", (指标,)
        ).fetchall()
    finally:
        conn.close()


def test_错阈影子草稿不入正式对账():
    _置({"PM25下限": "0", "PM25上限": "75", **浊度门})
    报告 = 装载.装一批({
        "报文": [{
            "报文编号": "B-浊-40",
            "站点键": "站-湖西",
            "指标键": "浊度",
            "读数": 40.0,
            "观测时": "2026-11-24T09:10:00Z",
            # 声明按 PM25 的气阈裁决 → 错阈；草稿会「过门槛」，正式不得入栏
            "门槛指标键": "PM25",
        }]
    })
    assert 报告["入栏"] == 0, 报告
    assert 报告["坏点"] == 1, 报告
    assert 报告.get("影子归档") == 1, 报告

    影子 = 目录.影子列表()
    assert any(r["报文编号"] == "B-浊-40" for r in 影子), 影子
    草 = next(r for r in 影子 if r["报文编号"] == "B-浊-40")
    assert 草["只读"] == 1, 草
    assert ("入栏" in 草["草稿命运"]) or ("过门槛" in 草["草稿命运"]), 草
    assert "错指标" in 草["原因"], 草

    # 影子草稿虽会过门槛，正式账不得增行
    assert len(目录.缓冲列表()) == 0
    assert _汇总("浊度") == []

    g = 贯验.跑一次()
    assert g["汇总报文"] == 0, g
    assert g["已汇总缓冲"] == 0, g
    assert g["影子笔数"] >= 1, g
    assert g["是否对齐"] is True, g


def test_改门槛后旧指纹命运拒回刷进影子():
    _置({"PM25下限": "0", "PM25上限": "75", **浊度门})
    r = 装载.装一批({
        "报文": [{
            "报文编号": "B-浊-1.2",
            "站点键": "站-湖西",
            "指标键": "浊度",
            "读数": 1.2,
            "观测时": "2026-11-24T09:20:00Z",
        }]
    })
    assert r["入栏"] == 1, r

    # 门槛改紧（0,1）：旧读数 1.2 的旧命运不得回刷进新门槛的正式汇总
    _置({"门槛:浊度:上限": "1"})

    结 = 结栏.结当前栏()
    assert 结["归档过时"] == 1, 结
    assert 结["汇总数"] == 0, 结
    assert _汇总("浊度") == []

    影子 = 目录.影子列表()
    草 = next(r for r in 影子 if r["报文编号"] == "B-浊-1.2")
    assert "过时" in 草["原因"] or "拒回刷" in 草["原因"], 草
    assert "入栏" in 草["草稿命运"] or "过门槛" in 草["草稿命运"], 草

    # 过时点仍留在缓冲，便于页面区分，但命运不是「已汇总」
    在栏 = [x for x in 目录.缓冲列表() if x["报文编号"] == "B-浊-1.2"]
    assert 在栏 and 在栏[0]["命运"] != "已汇总", 在栏

    g = 贯验.跑一次()
    assert g["汇总报文"] == 0, g
    assert g["已汇总缓冲"] == 0, g
    assert g["是否对齐"] is True, g
